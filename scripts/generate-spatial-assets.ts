import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { SPATIAL_CATALOG } from '../packages/contracts/src/spatial';
import { exportSpatialAsset } from '../apps/web/src/lib/spatial/build-assets';

// GLTFExporter uses FileReader for buffers. Node's Blob provides the same bytes.
class BlobReader {
  result: ArrayBuffer | string | null = null;
  onloadend?: () => void;
  readAsArrayBuffer(blob: Blob) { void blob.arrayBuffer().then(value => { this.result = value; this.onloadend?.(); }); }
  readAsDataURL(blob: Blob) { void blob.arrayBuffer().then(value => { this.result = `data:${blob.type};base64,${Buffer.from(value).toString('base64')}`; this.onloadend?.(); }); }
}
Object.assign(globalThis, { FileReader: BlobReader });
async function main() {
const root = resolve(__dirname, '..'), destination = resolve(root, 'apps/web/public/models');
await mkdir(destination, { recursive: true });
const hashes: Record<string, string> = {}, manifest = [];
for (const model of SPATIAL_CATALOG) {
  const asset = await exportSpatialAsset(model.id);
  if (asset.bytes.byteLength > model.budget.maxBytes || asset.triangles > model.budget.maxTriangles || asset.meshes > model.budget.maxMeshes) throw new Error(`${model.id}: asset exceeds its performance budget.`);
  for (const part of model.parts) for (const name of part.meshNames) if (!asset.meshNames.includes(name)) throw new Error(`${model.id}: missing semantic part ${name}.`);
  hashes[model.id] = createHash('sha256').update(asset.bytes).digest('hex');
  await writeFile(resolve(destination, `${model.id}.glb`), asset.bytes);
  manifest.push({ ...model, checksum: hashes[model.id], generated: { bytes: asset.bytes.byteLength, triangles: asset.triangles, meshes: asset.meshes, textures: 0, generator: 'scripts/generate-spatial-assets.ts', generatorVersion: '1.0.0' } });
  process.stdout.write(`${model.id}: ${asset.bytes.byteLength} bytes, ${asset.triangles} triangles, ${asset.meshes} meshes\n`);
}
await writeFile(resolve(destination, 'manifest.json'), JSON.stringify({ schemaVersion: 1, assets: manifest }, null, 2) + '\n');
await writeFile(resolve(root, 'packages/contracts/src/spatial-assets.generated.ts'), '// Regenerated by scripts/generate-spatial-assets.ts. No remote assets.\nexport const SPATIAL_ASSET_HASHES: Record<string, string> = ' + JSON.stringify(hashes, null, 2) + ';\n');
}
void main().catch(error => { process.stderr.write(`${error instanceof Error ? error.message : 'Asset generation failed'}\n`); process.exitCode = 1; });
